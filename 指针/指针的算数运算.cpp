#include <iostream>
 
int main() {
    // 定义一个数组
    int arr[] = {10, 20, 30, 40, 50};
    
    // 定义一个指向数组第一个元素的指针
    int* ptr = arr;
    
    // 输出指针指向的元素
    std::cout << "指针当前指向的元素: " << *ptr << std::endl;
    
    // 递增指针
    ptr++; 
    
    // 输出指针指向的元素
    std::cout << "递增指针后指向的元素: " << *ptr << std::endl;
    
    return 0;
}

